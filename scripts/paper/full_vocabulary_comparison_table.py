"""Render the all-target full-training-vocabulary comparison from verified exports.

Presentation only: never train, select checkpoints, retrieve again, resample,
or overwrite author-owned manuscript text.
"""
from __future__ import annotations

import csv
import hashlib
import json
import math
from pathlib import Path
import statistics

ROOT = Path(__file__).resolve().parents[2]
EXPORT = ROOT / 'data/results/exports'
TABLE = ROOT / 'paper/tables/full_vocab_comparison_v2_test.tex'
DATASETS = (('pallier2025', 'Pallier2025'), ('chineseeeg2_littleprince', 'ChineseEEG-2'))
METRICS = (('macro_recall_at_10', r'Macro Top-$10$'),
           ('micro_recall_at_10', r'Micro Top-$10$'),
           ('macro_recall_at_1', r'Macro Top-$1$'),
           ('micro_recall_at_1', r'Micro Top-$1$'))


def read_csv(path):
    with Path(path).open(encoding='utf-8-sig', newline='') as f:
        return list(csv.DictReader(f))


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def verified_rows():
    report = json.loads((EXPORT / 'full_vocabulary_context_test_v2_summary.json').read_text(encoding='utf-8'))
    assert report['status'] == 'verified_complete'
    assert report['oov_policy'] == 'retain_all_targets_as_errors'
    assert report['candidate_policy'] == 'full_frozen_training_vocabulary'
    assert report['supplementary_intervals'] and not report['new_p_tests']
    for relative, expected in report['exports'].items():
        assert sha(ROOT / relative) == expected, relative
    rows = [r for r in read_csv(EXPORT / 'full_vocabulary_context_test_v2_summary.csv') if r['population'] == 'all_words']
    seeds = [r for r in read_csv(EXPORT / 'full_vocabulary_context_test_v2_by_seed.csv') if r['population'] == 'all_words']
    differences = [r for r in read_csv(EXPORT / 'full_vocabulary_context_test_v2_difference_by_seed.csv') if r['population'] == 'all_words']
    assert len(rows) == 8
    for row in rows:
        dataset, metric = row['dataset'], row['metric']
        means = {}
        for condition, field in (('local_r2', 'local_r2_mean'), ('full_context', 'full_context_mean')):
            part = [r for r in seeds if r['dataset'] == dataset and r['condition'] == condition]
            assert {int(r['seed']) for r in part} == {0, 1, 2} and len(part) == 3
            for r in part:
                for key in ('candidate_count', 'query_count', 'target_count', 'oov_queries'):
                    assert int(r[key]) == int(row[key]), (dataset, condition, key)
            means[condition] = statistics.mean(float(r[metric]) for r in part)
            assert math.isclose(means[condition], float(row[field]), abs_tol=1e-12)
        assert math.isclose(means['local_r2'] - means['full_context'], float(row['effect']), abs_tol=1e-12)
        part = [r for r in differences if r['dataset'] == dataset and r['metric'] == metric]
        assert len(part) == 3 and {int(r['seed']) for r in part} == {0, 1, 2}
        assert math.isclose(statistics.mean(float(r['effect']) for r in part), float(row['effect']), abs_tol=1e-12)
    return rows


def render_table(rows):
    lines = [
        '% Presentation only: full_vocabulary_context_test_v2_summary.csv, population=all_words.',
        '% Generated by scripts/paper/full_vocabulary_comparison_table_test_v2.py.',
        r'\begingroup', r'\small', r'\setlength{\tabcolsep}{4pt}', r'\renewcommand{\arraystretch}{1.12}',
        r'\begin{tabular}{@{}llrrl@{}}', r'\toprule',
        r'数据集 & 指标 & 局部 $k=2$ (\%) & 完整上下文 (\%) & 差值及 $95\%$ 区间 (pp) \\',
        r'\midrule',
    ]
    for index, (dataset, label) in enumerate(DATASETS):
        if index:
            lines.append(r'\midrule')
        for j, (metric, metric_label) in enumerate(METRICS):
            row = next(r for r in rows if r['dataset'] == dataset and r['metric'] == metric)
            local, full = (f'{float(row[key]) * 100:.2f}' for key in ('local_r2_mean', 'full_context_mean'))
            effect = f'{float(row["effect"]) * 100:+.2f}'
            lower, upper = (f'{float(row[key]) * 100:.2f}' for key in ('ci_lower', 'ci_upper'))
            interval = f'${effect}\\ [{lower},{upper}]$'
            lines.append(' & '.join((label if j == 0 else '', metric_label, local, full, interval)) + r' \\')
    lines += [r'\bottomrule', r'\end{tabular}', r'\endgroup', '']
    return '\n'.join(lines)


def main():
    rows = verified_rows()
    TABLE.write_text(render_table(rows), encoding='utf-8', newline='\n')
    print(json.dumps({'table': TABLE.relative_to(ROOT).as_posix(), 'rows': len(rows),
                      'population': 'all_words', 'existing_exports_verified': True}))


if __name__ == '__main__':
    main()
